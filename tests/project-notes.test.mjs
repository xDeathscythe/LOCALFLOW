import assert from 'node:assert/strict';
import { mkdtempSync, mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import { tmpdir } from 'node:os';
import { join, resolve } from 'node:path';
import codex from '../electron/codex-client.cjs';
import { createNiwaAgent } from '../electron/niwa-agent.mjs';
import { createNotesStore } from '../electron/notes-store.mjs';

import { TestClient } from './agent-client-fixture.mjs';
const original = codex.CodexClient;
codex.CodexClient = TestClient;
const directory = mkdtempSync(join(tmpdir(), 'localflow-projects-'));
const options = { directory, appRoot: resolve('.'), binary: () => '', notify: () => {}, speak: async () => {} };
let agent = createNiwaAgent(options);
try {
  const md = '# Извештај\n\n## 日本語\n\n- [x] العربية\n\n| Name | Value |\n| --- | --- |\n| a | **b** |\n\n```ts\nconst value = 1;\n```';
  const notes = agent.notes;
  notes.importLegacy([{ id: 'inbox', kind: 'folder', label: 'Inbox', children: [{ id: 'old', kind: 'note', label: 'Old note', content: md }] }]);
  assert.equal(notes.read('old').content, md);
  assert.equal(readFileSync(notes.read('old').path, 'utf8'), md);
  const before = notes.read('old');
  notes.save({ ...before, content: `${md}\n\nNew paragraph` });
  assert.throws(() => notes.save({ ...before, content: 'stale' }), /changed elsewhere/);
  const external = notes.read('old'); writeFileSync(external.path, 'External editor');
  assert.throws(() => notes.save(external), /changed elsewhere/);
  assert.throws(() => notes.create({ kind: 'note', label: 'bad', parentId: 'missing' }), /folder/);
  assert.throws(() => createNotesStore(join(directory, 'invalid-import')).importLegacy([{ id: '../outside', kind: 'note', label: 'bad', content: '' }]), /Invalid/);
  notes.remove('old'); assert.equal(readFileSync(external.path, 'utf8'), 'External editor', 'Removed notes remain recoverable');
  assert.equal(createNotesStore(directory).list().items[0].children.length, 0);
  await agent.connect();
  const homeThread = TestClient.current.threadId;
  const toolSpecs = TestClient.current.calls.find(call => call.method === 'thread/start').params.dynamicTools;
  assert(toolSpecs.some(tool => tool.name === 'notes_create'));
  TestClient.current.emit('request', { id: 99, method: 'item/tool/call', params: { threadId: homeThread, callId: 'n', tool: 'notes_create', arguments: { label: 'Voice report', content: md } } });
  await new Promise(resolve => setImmediate(resolve));
  assert.equal(TestClient.current.response.result.success, true);
  assert(notes.list().items.some(item => item.label === 'Voice report'));
  TestClient.current.notify('item/completed', { item: { id: 'home-message', type: 'agentMessage', text: 'Niwa home' } });
  const projectPath = join(directory, 'project'), subPath = join(projectPath, '子目录'); mkdirSync(subPath, { recursive: true });
  const project = agent.addProject({ path: projectPath });
  const child = project;
  assert.throws(() => agent.addProject({ path: directory, parentId: project.id }), /subfolders/);
  agent.openFolder(child.id); const firstId = agent.projects().activeId;
  assert.equal(agent.snapshot().settings.cwd, projectPath);
  assert.equal(agent.snapshot().messages.length, 0);
  await agent.send('Prvi chat 日本語');
  assert.throws(() => agent.selectChat('niwa'), /Finish/);
  TestClient.current.notify('turn/diff/updated', { diff: 'first-diff' });
  TestClient.current.notify('turn/completed', { turn: { status: 'completed' } });
  const firstThread = TestClient.current.threadId;
  await agent.configure({ effort: 'high' });
  agent.newChat(child.id); assert.notEqual(agent.projects().activeId, firstId);
  await agent.connect(); assert.notEqual(TestClient.current.threadId, firstThread); assert.equal(agent.snapshot().diff, '');
  agent.selectChat(firstId); await agent.connect();
  assert.equal(TestClient.current.threadId, firstThread); assert.equal(agent.snapshot().settings.effort, 'high'); assert.equal(agent.snapshot().diff, 'first-diff');
  assert.equal(agent.snapshot().messages[0].content, 'Prvi chat 日本語');
  agent.selectChat('niwa'); await agent.connect(); assert.equal(TestClient.current.threadId, homeThread); assert.equal(agent.snapshot().messages[0].content, 'Niwa home');
  await agent.configure({ access: 'read' }); await agent.connect();
  TestClient.current.emit('request', { id: 100, method: 'item/tool/call', params: { threadId: TestClient.current.threadId, callId: 'n', tool: 'notes_create', arguments: { label: 'Forbidden', content: '' } } });
  await new Promise(resolve => setImmediate(resolve)); assert.equal(TestClient.current.response.result.success, false);
  agent.selectChat(firstId); await agent.close(); agent = createNiwaAgent(options);
  assert.equal(agent.projects().activeId, firstId); assert.equal(agent.snapshot().settings.cwd, projectPath); assert.equal(agent.snapshot().messages[0].content, 'Prvi chat 日本語');
  console.log('PROJECT_NOTES_OK: Markdown migration, disk persistence, revision conflicts, note tool parity, permissions, flat project validation, chat/thread isolation and restart');
} finally { await agent.close(); codex.CodexClient = original; }
